-- Educational dataset. Nutrition relationships are for analytics
-- practice and do NOT represent disease cures or individualized care.
-- ================================================================
DROP DATABASE IF EXISTS FoodHealthAnalytics;
CREATE DATABASE FoodHealthAnalytics CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE FoodHealthAnalytics;

CREATE TABLE Food_Categories (
    CategoryID INT PRIMARY KEY AUTO_INCREMENT,
    CategoryName VARCHAR(80) NOT NULL UNIQUE,
    Description VARCHAR(255)
);

CREATE TABLE Foods (
    FoodID INT PRIMARY KEY AUTO_INCREMENT,
    FoodName VARCHAR(120) NOT NULL UNIQUE,
    CategoryID INT NOT NULL,
    FoodGroup VARCHAR(80) NOT NULL,
    CaloriesPer100g DECIMAL(7,2) NOT NULL,
    ProteinPer100g DECIMAL(7,2) NOT NULL,
    CarbsPer100g DECIMAL(7,2) NOT NULL,
    FiberPer100g DECIMAL(7,2) NOT NULL,
    FatPer100g DECIMAL(7,2) NOT NULL,
    Omega3Per100g DECIMAL(7,2) NOT NULL,
    FOREIGN KEY (CategoryID) REFERENCES Food_Categories(CategoryID)
);
select * from foods;
alter table foods add column temper decimal(7,2) not null;
alter table foods drop temper;

CREATE TABLE Nutrients (
    NutrientID INT PRIMARY KEY AUTO_INCREMENT,
    NutrientName VARCHAR(80) NOT NULL UNIQUE,
    Unit VARCHAR(30) NOT NULL,
    NutrientGroup VARCHAR(60) NOT NULL
);

CREATE TABLE Food_Nutrients (
    FoodID INT NOT NULL,
    NutrientID INT NOT NULL,
    AmountPer100g DECIMAL(10,3) NOT NULL,
    PRIMARY KEY (FoodID, NutrientID),
    FOREIGN KEY (FoodID) REFERENCES Foods(FoodID),
    FOREIGN KEY (NutrientID) REFERENCES Nutrients(NutrientID)
);

CREATE TABLE Health_Conditions (
    ConditionID INT PRIMARY KEY AUTO_INCREMENT,
    ConditionName VARCHAR(100) NOT NULL UNIQUE,
    ConditionGroup VARCHAR(80) NOT NULL,
    Description VARCHAR(500)
);

CREATE TABLE Dietary_Goals (
    GoalID INT PRIMARY KEY AUTO_INCREMENT,
    GoalName VARCHAR(100) NOT NULL UNIQUE,
    Description VARCHAR(500)
);

CREATE TABLE Condition_Goals (
    ConditionID INT NOT NULL,
    GoalID INT NOT NULL,
    PriorityLevel ENUM('High','Medium','Low') NOT NULL,
    Notes VARCHAR(500),
    PRIMARY KEY (ConditionID, GoalID),
    FOREIGN KEY (ConditionID) REFERENCES Health_Conditions(ConditionID),
    FOREIGN KEY (GoalID) REFERENCES Dietary_Goals(GoalID)
);

CREATE TABLE Food_Health_Benefits (
    FoodID INT NOT NULL,
    ConditionID INT NOT NULL,
    GoalID INT NOT NULL,
    SuitabilityScore DECIMAL(5,2) NOT NULL,
    EvidenceLevel ENUM('General','Moderate','Strong') NOT NULL,
    BenefitNote VARCHAR(500),
    PRIMARY KEY (FoodID, ConditionID, GoalID),
    FOREIGN KEY (FoodID) REFERENCES Foods(FoodID),
    FOREIGN KEY (ConditionID) REFERENCES Health_Conditions(ConditionID),
    FOREIGN KEY (GoalID) REFERENCES Dietary_Goals(GoalID)
);

CREATE TABLE Serving_Units (
    ServingID INT PRIMARY KEY AUTO_INCREMENT,
    FoodID INT NOT NULL,
    ServingDescription VARCHAR(100) NOT NULL,
    ApproxGrams DECIMAL(7,2) NOT NULL,
    FOREIGN KEY (FoodID) REFERENCES Foods(FoodID)
);

CREATE TABLE Dietary_Guidelines (
    GuidelineID INT PRIMARY KEY AUTO_INCREMENT,
    ConditionID INT NOT NULL,
    GuidelineText VARCHAR(700) NOT NULL,
    SourceType VARCHAR(100) NOT NULL,
    FOREIGN KEY (ConditionID) REFERENCES Health_Conditions(ConditionID)
);

CREATE INDEX idx_food_category ON Foods(CategoryID);
CREATE INDEX idx_food_nutrients_nutrient ON Food_Nutrients(NutrientID);
CREATE INDEX idx_benefits_condition ON Food_Health_Benefits(ConditionID);
CREATE INDEX idx_benefits_goal ON Food_Health_Benefits(GoalID);

